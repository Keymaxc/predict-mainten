drop table if exists error_logs       cascade;
drop table if exists failures         cascade;
drop table if exists maintenance_logs cascade;
drop table if exists sensor_readings  cascade;
drop table if exists machines         cascade;

create table machines (
    machine_id      integer generated by default as identity primary key,
    machine_name    text    not null unique,
    machine_type    text    not null,          
    machine_model   text    not null,           
    production_line text    not null,           
    install_date    date    not null,          
    status          text    not null default 'active'
                    check (status in ('active', 'maintenance', 'retired')),
    created_at      timestamptz not null default now()
);


create table sensor_readings (
    reading_id    bigint generated by default as identity primary key,
    machine_id    integer     not null references machines (machine_id) on delete cascade,
    reading_time  timestamptz not null,
    voltage       numeric(7,2),      
    rotation_rpm  numeric(8,2),      
    pressure      numeric(7,2),
    vibration     numeric(7,2),
    temperature   numeric(6,2),      
    unique (machine_id, reading_time)
);

create table maintenance_logs (
    maintenance_id    bigint generated by default as identity primary key,
    machine_id        integer     not null references machines (machine_id) on delete cascade,
    maintenance_date  timestamptz not null,
    component         text        not null
                      check (component in ('bearing', 'motor', 'hydraulic_pump', 'control_board')),
    maintenance_type  text        not null
                      check (maintenance_type in ('preventive', 'corrective')),
    cost_idr          numeric(14,0) not null default 0 check (cost_idr >= 0),
    downtime_hours    numeric(6,1)  not null default 0 check (downtime_hours >= 0)
);

create table failures (
    failure_id      bigint generated by default as identity primary key,
    machine_id      integer     not null references machines (machine_id) on delete cascade,
    failure_time    timestamptz not null,
    component       text        not null
                    check (component in ('bearing', 'motor', 'hydraulic_pump', 'control_board')),
    failure_type    text        not null,        
    severity        text        not null default 'medium'
                    check (severity in ('low', 'medium', 'high')),
    downtime_hours  numeric(6,1) not null default 0 check (downtime_hours >= 0)
);


create table error_logs (
    error_id           bigint generated by default as identity primary key,
    machine_id         integer     not null references machines (machine_id) on delete cascade,
    error_time         timestamptz not null,
    error_code         text        not null,     
    error_description  text,
    severity           text        not null default 'low'
                       check (severity in ('low', 'medium', 'high'))
);


create index idx_sensor_time        on sensor_readings  (reading_time);
create index idx_maintenance_lookup on maintenance_logs (machine_id, maintenance_date);
create index idx_failures_lookup    on failures         (machine_id, failure_time);
create index idx_errors_lookup      on error_logs       (machine_id, error_time);

alter table machines         enable row level security;
alter table sensor_readings  enable row level security;
alter table maintenance_logs enable row level security;
alter table failures         enable row level security;
alter table error_logs       enable row level security;

